assert.equal(result.models,5);assert.equal(result.runs,20);assert.equal(result.restores,103);assert.equal(result.advancing,83);assert.equal(result.terminal,20);
assert.equal(plan.runs.length,20);assert.equal(new Set(plan.runs.map(r=>r.modelIdentity)).size,5);
assert.equal(new Set(plan.runs.map(r=>r.runIdentity)).size,20);
assert(plan.experimentIdentity.length>0&&plan.comparisonCase.length>0);
for(const [i,row] of result.results.entries()) {
  assert.equal(row.runIdentity,plan.runs[i].runIdentity);assert.equal(row.modelIdentity,plan.runs[i].modelIdentity);assert.equal(row.orderedInputs,plan.runs[i].orderedInputs);
}
for(const a of plan.artifacts)assert.equal(sha(a.path),a.sha256,a.path);
assert.equal(tests.numPassedTests,15);assert.equal(tests.numFailedTests,0);
assert.equal(reference.numPassedTests,328);assert.equal(reference.numFailedTests,0);
assert.equal(read(p+'REAPPRAISAL_BUILD_REV1.json').status,'PASS');
const freeze=read(p+'campaign3-reappraisal-model-rev1/FREEZE.json');
assert.equal(freeze.models.length,5);for(const m of freeze.models)for(const a of m.files)assert.equal(sha(a.path),a.sha256,a.path);
assert.deepEqual(new Set(plan.runs.map(r=>r.modelIdentity)),new Set(freeze.models.map(m=>m.modelIdentity)));
const allocation=read('docs/formal/REAPPRAISAL_PUBLIC_ALLOCATION_TABLE.json');
assert.equal(allocation.namespace,1165);assert.deepEqual(allocation.records.map(r=>r.typeId),Array.from({length:15},(_,i)=>1025+i));
assert.equal(freeze.contractSha256,sha('docs/formal/REAPPRAISAL_PUBLIC_CONTRACT.md'));assert.equal(freeze.allocationSha256,sha('docs/formal/REAPPRAISAL_PUBLIC_ALLOCATION_TABLE.json'));
const files=[planPath,resultPath,p+'REAPPRAISAL_TESTS_REV1.json',p+'REAPPRAISAL_REFERENCE_TESTS_REV1.json',p+'REAPPRAISAL_BUILD_REV1.json',p+'CAMPAIGN3_REAPPRAISAL_QUALIFICATION.md','scripts/check-reappraisal-closure.mjs','docs/formal/REAPPRAISAL_PUBLIC_CONTRACT.md'];
const closure={status:'PASS',contract:'reappraisal-public/0.1-candidate',newModels:5,models:5,runs:20,prefixes:103,advancing:83,terminal:20,tests:15,referenceTests:328,artifacts:files.map(path=>({path,sha256:sha(path)}))};
const path=p+'REAPPRAISAL_CLOSURE_REV1.json';
if(process.argv.includes('--write'))fs.writeFileSync(path,JSON.stringify(closure,null,2)+'\n',{flag:'wx'});
