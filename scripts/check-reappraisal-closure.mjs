import fs from 'node:fs';
import assert from 'node:assert/strict';
import {createHash} from 'node:crypto';
const p='docs/planning/',read=path=>JSON.parse(fs.readFileSync(path)),sha=path=>createHash('sha256').update(fs.readFileSync(path)).digest('hex');
const planPath=p+'REAPPRAISAL_PUBLIC_PLAN_REV1.json',resultPath=p+'REAPPRAISAL_PUBLIC_RESULT_REV1.json';
const plan=read(planPath),result=read(resultPath),tests=read(p+'REAPPRAISAL_TESTS_REV1.json'),reference=read(p+'REAPPRAISAL_REFERENCE_TESTS_REV1.json');
